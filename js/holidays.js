// ===== 한국 공휴일 =====
const holidays = (() => {

  // 고정 공휴일 (매년 동일, MM-DD)
  const FIXED = new Set([
    '01-01', // 신정
    '03-01', // 삼일절
    '05-05', // 어린이날
    '06-06', // 현충일
    '08-15', // 광복절
    '10-03', // 개천절
    '10-09', // 한글날
    '12-25', // 성탄절
  ]);

  // 음력 공휴일 (설날·추석 연휴, 부처님오신날, 대체공휴일) YYYY-MM-DD
  const LUNAR = new Set([
    // 2024
    '2024-02-09','2024-02-10','2024-02-11','2024-02-12', // 설날 연휴 + 대체
    '2024-05-06', // 어린이날 대체 (5/5 일요일)
    '2024-05-15', // 부처님오신날
    '2024-09-16','2024-09-17','2024-09-18',              // 추석 연휴

    // 2025
    '2025-01-28','2025-01-29','2025-01-30',              // 설날 연휴
    '2025-05-05', // 부처님오신날 (어린이날 동일)
    '2025-05-06', // 대체공휴일
    '2025-10-05','2025-10-06','2025-10-07','2025-10-08', // 추석 연휴 + 대체

    // 2026
    '2026-02-16','2026-02-17','2026-02-18',              // 설날 연휴
    '2026-05-24', // 부처님오신날
    '2026-05-25', // 대체공휴일 (5/24 일요일)
    '2026-09-24','2026-09-25','2026-09-26',              // 추석 연휴

    // 2027
    '2027-02-05','2027-02-06','2027-02-07','2027-02-08', // 설날 연휴 + 대체
    '2027-05-13', // 부처님오신날
    '2027-10-14','2027-10-15','2027-10-16',              // 추석 연휴

    // 2028
    '2028-01-25','2028-01-26','2028-01-27',              // 설날 연휴
    '2028-05-02', // 부처님오신날
    '2028-10-02','2028-10-03','2028-10-04',              // 추석 연휴

    // 2029
    '2029-02-12','2029-02-13','2029-02-14',              // 설날 연휴
    '2029-05-20', // 부처님오신날
    '2029-09-21','2029-09-22','2029-09-23',              // 추석 연휴

    // 2030
    '2030-02-02','2030-02-03','2030-02-04',              // 설날 연휴
    '2030-05-09', // 부처님오신날
    '2030-09-11','2030-09-12','2030-09-13',              // 추석 연휴
  ]);

  function isHoliday(dateStr) {
    if (!dateStr) return false;
    return LUNAR.has(dateStr) || FIXED.has(dateStr.slice(5));
  }

  return { isHoliday };
})();
